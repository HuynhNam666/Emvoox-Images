export type IconName = keyof typeof PATHS;

export function Icon({ name, className = "" }: { name: IconName; className?: string }) {
  return <svg className={`icon ${className}`} viewBox="0 0 24 24" aria-hidden="true">{PATHS[name]}</svg>;
}

export function Spinner() {
  return <span className="spinner" role="status" aria-label="Đang xử lý" />;
}

export type Tone = "ok" | "warn" | "bad" | "info" | "primary" | "";

export function Badge({ tone = "", children }: { tone?: Tone; children: ReactNode }) {
  return <span className={`badge ${tone}`}>{children}</span>;
}

export function Card({ title, sub, actions, children, flat, className = "" }: {
  title?: ReactNode; sub?: ReactNode; actions?: ReactNode; children: ReactNode; flat?: boolean; className?: string;
}) {
  return (
    <section className={`card${flat ? " flat" : ""} ${className}`}>
      {(title || actions) && (
        <header className="card-h">
          <div style={{ minWidth: 0 }}>
            <h3 className="card-title">{title}</h3>
            {sub && <p className="card-sub">{sub}</p>}
          </div>
          <span className="spacer" />
          {actions}
        </header>
      )}
      <div className="card-b">{children}</div>
    </section>
  );
}

export function Field({ label, hint, children }: { label: ReactNode; hint?: ReactNode; children: ReactNode }) {
  return (
    <label className="field">
      <span>{label}</span>
      {children}
      {hint && <span className="hint">{hint}</span>}
    </label>
  );
}

export function Alert({ tone = "info", children }: { tone?: "info" | "bad" | "warn" | "ok"; children: ReactNode }) {
  const icon: IconName = tone === "bad" ? "alert" : tone === "warn" ? "alert" : tone === "ok" ? "check" : "info";
  return (
    <div className={`alert ${tone === "info" ? "" : tone}`} role={tone === "bad" ? "alert" : undefined}>
      <Icon name={icon} className="sm" />
      <div className="alert-body">{children}</div>
    </div>
  );
}

export function Empty({ icon, title, children }: { icon: IconName; title: string; children?: ReactNode }) {
  return (
    <div className="empty">
      <div className="icon-wrap"><Icon name={icon} /></div>
      <h3>{title}</h3>
      {children && <p style={{ maxWidth: "42ch" }}>{children}</p>}
    </div>
  );
}

export function PageHead({ title, sub, actions }: { title: string; sub?: string; actions?: ReactNode }) {
  return (
    <div className="page-head">
      <div>
        <h1 className="page-title">{title}</h1>
        {sub && <p className="page-sub">{sub}</p>}
      </div>
      {actions}
    </div>
  );
}

export function Segmented<T extends string>({ value, options, onChange, label }: {
  value: T; options: { value: T; label: string }[]; onChange: (v: T) => void; label: string;
}) {
  return (
    <div className="seg" role="group" aria-label={label}>
      {options.map((o) => (
        <button key={o.value} type="button" aria-pressed={value === o.value} onClick={() => onChange(o.value)}>{o.label}</button>
      ))}
    </div>
  );
}
